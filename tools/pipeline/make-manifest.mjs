#!/usr/bin/env node
// Turns an approved candidate + a built Release of vapor-artifacts into the files a listing PR
// needs: games/<slug>/game.json, audits/<slug>.json and pr-body.md.
//
//   node tools/pipeline/make-manifest.mjs --candidate crawl-output/Owner__repo.json \
//        --slug my-game --title "My Game" --entry my-game/index.html --tag my-game-1
//
// Nothing is invented: license, commit and tags come from the candidate record; the artifact
// URL, size and SHA-256 come from the downloaded Release zip; the license of the assets is the
// list the automatic audit actually found (assets_policy "open" requires verdict auto-open).
// Steps: download -> hash -> `vapor audit` (blocks stop everything) -> extract -> browser smoke
// test (infers saves.paths) -> write files. A person reviews and merges the PR.

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { smoke } from "./smoke.mjs";

const ARTIFACTS_REPO = "lucasgmagalhaes/vapor-artifacts";
const URL_PREFIX = `https://github.com/${ARTIFACTS_REPO}/releases/download/`;
/** Emscripten/SDL runtime glue that every build contains and the game window CSP neutralizes. */
export const BASELINE_ACCEPT = ["capability-camera-mic", "capability-popup", "capability-clipboard", "capability-navigation", "dynamic-code"];

/** Pure: assembles game.json from verified inputs. Throws instead of guessing. */
export function buildManifest(candidate, { slug, title, entry, tag, sha256, size, savesPaths }) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) throw new Error(`invalid slug: ${slug}`);
  const audit = candidate.asset_audit;
  if (!audit || audit.verdict !== "auto-open") {
    throw new Error(`asset audit verdict is "${audit?.verdict ?? "missing"}": only auto-open candidates become open; use a bring-your-own flow otherwise`);
  }
  if (!candidate.license?.spdx || candidate.license.spdx === "NOASSERTION") throw new Error("code license unknown");
  if (!/^[0-9a-f]{64}$/i.test(sha256) || !(size > 0)) throw new Error("bad artifact hash/size");
  if (!savesPaths?.length) throw new Error("no saves.paths inferred: run the smoke test and review");
  return {
    schema: 1,
    slug,
    title,
    authors: [candidate.repo.split("/")[0]],
    source: { repo: candidate.url, commit: candidate.commit_checked },
    license: { code: candidate.license.spdx, assets: audit.licenses_seen.join(", ") },
    assets_policy: "open",
    artifact: { url: `${URL_PREFIX}${tag}/${slug}.zip`, sha256: sha256.toLowerCase(), size, entry },
    saves: { paths: savesPaths, version: 1 },
    tags: (candidate.topics ?? []).slice(0, 5),
    contact: `${candidate.url}/issues`,
  };
}

export function prBody({ manifest, candidate, smokeReport, auditOk, auditLog }) {
  const a = candidate.asset_audit;
  const lines = [
    `## Add ${manifest.title}`,
    "",
    `Generated by \`tools/pipeline/make-manifest.mjs\`. **A person must read the license files before merging.**`,
    "",
    `- Source: ${manifest.source.repo} @ \`${manifest.source.commit}\` (${manifest.license.code})`,
    `- Artifact: ${manifest.artifact.url} (${manifest.artifact.size} bytes, sha256 \`${manifest.artifact.sha256}\`)`,
    `- Assets: ${a.assets.files} files, ${Math.round(a.coverage.strong * 100)}% covered by ${a.licenses_seen.join(", ")}`,
    `- Smoke test: ${smokeReport.ok ? "passed" : "**FAILED**: " + smokeReport.reasons.join("; ")}`,
    `- saves.paths (inferred, broad; narrow if possible): ${manifest.saves.paths.join(", ")}`,
    `- Security audit: ${auditOk ? "clean (runtime-glue warnings accepted by the pipeline baseline)" : "**needs a reviewer**: warnings not in the baseline, see below"}`,
    "",
    "### Audit output",
    "```",
    auditLog.trim(),
    "```",
    "",
    "### Checklist",
    "- [ ] I read the code and asset license files at the commit above",
    "- [ ] No duplicate of an existing game (`vapor validate` warnings reviewed)",
    "- [ ] The audited warnings are acceptable",
  ];
  return lines.join("\n") + "\n";
}

function sh(cmd, args, opts = {}) {
  return execFileSync(cmd, args, { encoding: "utf8", maxBuffer: 256 * 1024 * 1024, ...opts });
}

async function main() {
  const args = process.argv.slice(2);
  const get = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
  const need = (n) => get(n) ?? (() => { throw new Error(`missing ${n}`); })();
  const candidatePath = need("--candidate"), slug = need("--slug"), title = need("--title"), entry = need("--entry"), tag = need("--tag");
  const root = get("--root") ?? ".";
  const channel = get("--channel") ?? process.env.SMOKE_CHANNEL ?? "chrome";
  const candidate = JSON.parse(readFileSync(candidatePath, "utf8"));

  const work = mkdtempSync(path.join(tmpdir(), "vapor-mm-"));
  sh("gh", ["release", "download", tag, "-R", ARTIFACTS_REPO, "-p", `${slug}.zip`, "-D", work, "--clobber"]);
  const zip = path.join(work, `${slug}.zip`);
  const bytes = readFileSync(zip);
  const sha256 = createHash("sha256").update(bytes).digest("hex");

  const vapor = ["run", "-q", "-p", "vapor-cli", "--"];
  // 1. Hard stop on blocking findings.
  sh("cargo", [...vapor, "audit", zip, "--slug", slug, "--scan-only"], { cwd: root });
  // 2. Smoke test (also infers saves.paths).
  const dir = path.join(work, "x");
  mkdirSync(dir);
  sh("unzip", ["-q", zip, "-d", dir]);
  const report = await smoke(dir, entry, { channel });
  const savesPaths = report.suggested_saves_paths;
  // 3. Manifest + audit record.
  const manifest = buildManifest(candidate, { slug, title, entry, tag, sha256, size: bytes.length, savesPaths });
  mkdirSync(path.join(root, "games", slug), { recursive: true });
  writeFileSync(path.join(root, "games", slug, "game.json"), JSON.stringify(manifest, null, 2) + "\n");
  let auditOk = true, auditLog = "";
  try {
    auditLog = sh("cargo", [...vapor, "audit", zip, "--slug", slug, "--accept", BASELINE_ACCEPT.join(","), "--notes", `Automatic pipeline audit. Runtime-glue warnings (${BASELINE_ACCEPT.join(", ")}) accepted by baseline: the game window CSP blocks network access.`, "--write", "--root", root], { cwd: root });
  } catch (e) {
    auditOk = false;
    auditLog = `${e.stdout ?? ""}${e.stderr ?? ""}`;
  }
  writeFileSync(path.join(root, "pr-body.md"), prBody({ manifest, candidate, smokeReport: report, auditOk, auditLog }));
  console.log(JSON.stringify({ slug, ok: report.ok && auditOk, smoke_ok: report.ok, audit_ok: auditOk, saves_paths: savesPaths }, null, 2));
  process.exit(report.ok && auditOk ? 0 : 1);
}

if (process.argv[1] && path.basename(process.argv[1]) === "make-manifest.mjs") {
  main().catch((e) => { console.error(`error: ${e.message}`); process.exit(2); });
}
