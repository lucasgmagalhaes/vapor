#!/usr/bin/env node
// Generates a `build-<slug>.yml` for lucasgmagalhaes/vapor-artifacts from a candidate record.
//
//   node tools/pipeline/gen-build.mjs --candidate crawl-output/Owner__repo.json --slug my-game \
//        --checkout <dir of a clone at the pinned commit> [--out build-my-game.yml]
//
// The workflow it writes pins the source commit, builds with Emscripten, packages ONLY build
// outputs plus the license texts, runs `vapor audit --scan-only` (a blocking finding fails the
// build) and publishes a Release `<slug>-<run number>` with the zip hash and size in the job
// summary. The recipe is detected from the repository's own files; when none is found the game
// stays `needs-port`. The generated file is a starting point: a person reviews it before the
// first run, and the first run decides whether the recipe works.

import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";

export const EMSDK_VERSION = "3.1.74";

/** Pure: picks a build recipe from the file list and a way to read file text. */
export function detectRecipe(paths, readText) {
  const has = (re) => paths.some((p) => re.test(p));
  const docker = paths.find((p) => /(^|\/)emscripten\/Dockerfile[^/]*$/i.test(p));
  if (docker) {
    const dir = path.posix.dirname(docker);
    return { kind: "emscripten-dockerfile", dockerfile: docker, context: dir === "." ? "." : dir,
      note: "upstream ships an Emscripten Dockerfile: read it to see which outputs it produces" };
  }
  if (has(/^CMakeLists\.txt$/)) {
    const cmake = readText("CMakeLists.txt") ?? "";
    const readme = paths.filter((p) => /^readme/i.test(p)).map((p) => readText(p) ?? "").join("\n");
    if (/EMSCRIPTEN|emscripten/i.test(cmake) || /emcmake|emscripten/i.test(readme)) {
      return { kind: "cmake-emscripten", note: "CMake project with Emscripten support" };
    }
  }
  const mk = has(/^Makefile$/) ? readText("Makefile") ?? "" : "";
  if (/emcc|emmake|EMSCRIPTEN/i.test(mk)) return { kind: "makefile-emscripten", note: "Makefile mentions emcc/emmake" };
  return null;
}

const ghx = (e) => "${{ " + e + " }}";

function buildStep(recipe) {
  switch (recipe.kind) {
    case "cmake-emscripten":
      return [
        "          emcmake cmake -S . -B build -DCMAKE_BUILD_TYPE=Release",
        "          cmake --build build -j\"$(nproc)\"",
        "          echo build > ../outdir",
      ];
    case "makefile-emscripten":
      return [
        "          emmake make -j\"$(nproc)\"",
        "          echo . > ../outdir",
      ];
    case "emscripten-dockerfile":
      return [
        `          docker build -t slug-build -f ${recipe.dockerfile} ${recipe.context}`,
        "          mkdir -p ../dockerout",
        "          cid=$(docker create slug-build)",
        "          docker cp \"$cid\":/out/. ../dockerout/ || docker cp \"$cid\":/src/build/. ../dockerout/",
        "          docker rm \"$cid\"",
        "          echo ../dockerout > ../outdir",
      ];
    default:
      throw new Error(`unknown recipe: ${recipe.kind}`);
  }
}

/** Pure: the workflow text. Validates every interpolated value. */
export function renderWorkflow(candidate, slug, recipe) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(slug)) throw new Error(`invalid slug: ${slug}`);
  if (!/^[0-9a-f]{40}$/.test(candidate.commit_checked ?? "")) throw new Error("candidate has no pinned 40-hex commit");
  if (!/^https:\/\/github\.com\/[\w.-]+\/[\w.-]+$/.test(candidate.url ?? "")) throw new Error("candidate url is not a GitHub repository");
  if (!recipe) throw new Error("no build recipe detected (status stays needs-port)");
  const L = [];
  L.push(`name: build-${slug}`);
  L.push(`# GENERATED by vapor tools/pipeline/gen-build.mjs from the crawler record of ${candidate.repo}.`);
  L.push(`# Recipe: ${recipe.kind} (${recipe.note}). Review before the first run; the first run decides if it works.`);
  L.push(`# Builds ${candidate.url} (${candidate.license?.spdx ?? "unknown license"}) at a pinned commit and publishes`);
  L.push(`# a Release containing ${slug}.zip. The zip holds build outputs + license texts only.`);
  L.push("on:", "  workflow_dispatch:", "", "permissions:", "  contents: write", "");
  L.push("env:");
  L.push(`  SRC_REPO: ${candidate.url}`);
  L.push(`  SRC_COMMIT: ${candidate.commit_checked}`);
  L.push(`  EMSDK_VERSION: ${EMSDK_VERSION}`);
  L.push(`  SLUG: ${slug}`);
  L.push(`  TAG: ${slug}-${ghx("github.run_number")}`, "");
  L.push("jobs:", "  build:", "    runs-on: ubuntu-latest", "    steps:");
  L.push("      - uses: actions/checkout@v4");
  L.push("      - uses: mymindstorm/setup-emsdk@v14", "        with:", `          version: ${ghx("env.EMSDK_VERSION")}`);
  L.push("      - name: Fetch the source at the pinned commit", "        run: |",
    "          git init src && cd src",
    "          git remote add origin \"$SRC_REPO\"",
    "          git fetch --depth 1 origin \"$SRC_COMMIT\"",
    "          git checkout FETCH_HEAD");
  L.push("      - name: Build", "        working-directory: src", "        run: |", ...buildStep(recipe));
  L.push("      - name: Package build outputs and licenses", "        run: |",
    "          set -euo pipefail",
    "          out=\"pkg/$SLUG\"; mkdir -p \"$out\"",
    "          dir=\"src/$(cat outdir)\"; [ -d \"$dir\" ] || dir=\"$(cat outdir)\"",
    "          found=0",
    "          for ext in html js wasm data mem; do",
    "            for f in \"$dir\"/*.$ext; do [ -f \"$f\" ] && cp \"$f\" \"$out\"/ && found=1; done",
    "          done",
    "          [ \"$found\" = 1 ] || { echo \"no build outputs found in $dir\"; exit 1; }",
    "          for l in src/LICENSE* src/COPYING* src/LICENCE* src/CREDITS* src/AUTHORS*; do [ -f \"$l\" ] && cp \"$l\" \"$out\"/ || true; done",
    "          printf 'Source: %s @ %s\\nPackaged by https://github.com/%s\\n' \"$SRC_REPO\" \"$SRC_COMMIT\" \"$GITHUB_REPOSITORY\" > \"$out\"/SOURCE.txt",
    "          (cd pkg && zip -qr -X \"../$SLUG.zip\" \"$SLUG\")");
  L.push("      - name: Security audit (blocking findings fail the build)", "        run: |",
    "          git clone --depth 1 https://github.com/lucasgmagalhaes/vapor vapor-src",
    "          cargo run -q --manifest-path vapor-src/Cargo.toml -p vapor-cli -- audit \"$SLUG.zip\" --slug \"$SLUG\" --scan-only");
  L.push("      - name: Hash and size", "        id: hash", "        run: |",
    "          echo \"sha256=$(sha256sum \"$SLUG.zip\" | cut -d' ' -f1)\" >> \"$GITHUB_OUTPUT\"",
    "          echo \"size=$(stat -c %s \"$SLUG.zip\")\" >> \"$GITHUB_OUTPUT\"");
  L.push("      - uses: softprops/action-gh-release@v2", "        with:", `          tag_name: ${ghx("env.TAG")}`,
    `          name: ${slug} ${ghx("github.run_number")}`, `          files: ${slug}.zip`);
  L.push("      - name: Summary", "        run: |", "          {", "            echo \"### Published artifact\"",
    `            echo "- url: https://github.com/${ghx("github.repository")}/releases/download/${ghx("env.TAG")}/${slug}.zip"`,
    `            echo "- sha256: ${ghx("steps.hash.outputs.sha256")}"`,
    `            echo "- size: ${ghx("steps.hash.outputs.size")}"`,
    "          } >> \"$GITHUB_STEP_SUMMARY\"");
  return L.join("\n") + "\n";
}

function listFiles(dir) {
  const out = [];
  const walk = (d, rel) => {
    for (const e of readdirSync(d, { withFileTypes: true })) {
      if (e.name === ".git") continue;
      const r = rel ? `${rel}/${e.name}` : e.name;
      if (e.isDirectory()) { if (r.split("/").length < 3) walk(path.join(d, e.name), r); } else out.push(r);
    }
  };
  walk(dir, "");
  return out;
}

if (process.argv[1] && path.basename(process.argv[1]) === "gen-build.mjs") {
  const args = process.argv.slice(2);
  const get = (n) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
  const candidate = JSON.parse(readFileSync(get("--candidate") ?? "", "utf8"));
  const slug = get("--slug") ?? "";
  const checkout = get("--checkout");
  if (!checkout || !existsSync(checkout)) { console.error("pass --checkout <dir of a clone of the candidate at the pinned commit>"); process.exit(2); }
  const recipe = detectRecipe(listFiles(checkout), (p) => { try { return readFileSync(path.join(checkout, p), "utf8"); } catch { return null; } });
  try {
    const yml = renderWorkflow(candidate, slug, recipe);
    const out = get("--out") ?? `build-${slug}.yml`;
    writeFileSync(out, yml);
    console.log(`wrote ${out} (recipe: ${recipe.kind})`);
  } catch (e) { console.error(`error: ${e.message}`); process.exit(1); }
}
